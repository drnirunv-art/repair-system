where grp is null and name in ('รออะไหล่','รอผู้รับเหมา / ช่างภายนอก','รอหน่วยงานเปิดพื้นที่','รอจัดซื้อ / อนุมัติงบ','รอผู้แจ้งยืนยันเวลา','รอผลตรวจ / ผู้เชี่ยวชาญ');
