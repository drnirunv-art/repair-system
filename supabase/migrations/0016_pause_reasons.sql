  ('เข้าพื้นที่ไม่ได้ (Access)','รออนุมัติเข้าพื้นที่จากผู้เช่า / ผู้รับบริการ',105),
  ('เข้าพื้นที่ไม่ได้ (Access)','สภาพอากาศไม่เอื้ออำนวยต่อการปฏิบัติงาน',106),
